#!/usr/bin/env node

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const TARGET_COUNT = 20000;
const MIN_LEN = 3;
const MAX_LEN = 12;

const SOURCES = {
	frequency:
		'https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018/en/en_50k.txt',
	validity:
		'https://raw.githubusercontent.com/dwyl/english-words/master/words_alpha.txt',
	blocklist:
		'https://raw.githubusercontent.com/LDNOOBW/List-of-Dirty-Naughty-Obscene-and-Otherwise-Bad-Words/master/en',
};

const EXTRA_BLOCKED = [

	'anal', 'anus', 'arse', 'damn', 'erotic', 'genital', 'genitals',
	'hell', 'nazi', 'nazis', 'nude', 'nudes', 'pee', 'poo', 'poop',
	'rectum', 'urine',

	'ammo', 'ammunition', 'bayonet', 'bomb', 'bombed', 'bomber',
	'bombing', 'bombs', 'bullet', 'bullets', 'cannon', 'cannons',
	'grenade', 'grenades', 'gun', 'gunfire', 'gunman', 'gunmen',
	'gunner', 'guns', 'gunshot', 'gunshots', 'kill', 'killed',
	'killer', 'killers', 'killing', 'killings', 'kills', 'knife',
	'knives', 'massacre', 'missile', 'missiles', 'murder', 'murdered',
	'murderer', 'murderers', 'murders', 'pistol', 'pistols', 'rifle',
	'rifles', 'shooter', 'shooters', 'shotgun', 'shotguns', 'slaughter',
	'sniper', 'snipers', 'stab', 'stabbed', 'stabbing', 'sword',
	'swords', 'torpedo', 'war', 'warfare', 'warhead', 'wars', 'weapon',
	'weaponry', 'weapons',
];

async function readSource( localPath, url ) {
	if ( localPath ) {
		return readFileSync( localPath, 'utf8' );
	}
	const res = await fetch( url );
	if ( ! res.ok ) {
		throw new Error( `Fetch failed (${ res.status }): ${ url }` );
	}
	return res.text();
}

const [ , , freqPath, validPath, blockPath ] = process.argv;

const [ freqRaw, validRaw, blockRaw ] = await Promise.all( [
	readSource( freqPath, SOURCES.frequency ),
	readSource( validPath, SOURCES.validity ),
	readSource( blockPath, SOURCES.blocklist ),
] );

const valid = new Set(
	validRaw
		.split( /\r?\n/ )
		.map( ( line ) => line.trim().toLowerCase() )
		.filter( Boolean ),
);
const blocked = new Set(
	[
		...blockRaw.split( /\r?\n/ ).map( ( line ) => line.trim().toLowerCase() ),
		...EXTRA_BLOCKED,
	].filter( Boolean ),
);

const shape = /^[a-z]{3,12}$/;
const picked = [];
for ( const line of freqRaw.split( /\r?\n/ ) ) {
	if ( picked.length >= TARGET_COUNT ) {
		break;
	}
	const [ word ] = line.trim().split( /\s+/ );
	if (
		! word ||
		! shape.test( word ) ||
		! valid.has( word ) ||
		blocked.has( word )
	) {
		continue;
	}

	picked.push( word );
}

if ( picked.length < TARGET_COUNT ) {
	console.warn(
		`Only ${ picked.length } words survived filtering (target ${ TARGET_COUNT }).`,
	);
}

const rank = new Map( picked.map( ( word, index ) => [ word, index ] ) );
picked.sort( ( a, b ) => a.length - b.length || rank.get( a ) - rank.get( b ) );

const header = [
	'# OpenStation games dictionary — generated by bin/build-game-words.mjs. Do not hand-edit.',
	`# ${ picked.length } lowercase English words, ${ MIN_LEN }-${ MAX_LEN } letters,`,
	'# sorted by length (ascending) then usage frequency (descending).',
	'#',
	'# Sources:',
	'# - Frequency ranking: hermitdave/FrequencyWords (en_50k, 2018),',
	'#   derived from the OpenSubtitles corpus. License: CC-BY-SA 4.0.',
	'#   https://github.com/hermitdave/FrequencyWords',
	'# - Validity filter: dwyl/english-words (words_alpha). License: Unlicense.',
	'#   https://github.com/dwyl/english-words',
	'# - Profanity filter: LDNOOBW English list. License: CC-BY 4.0.',
	'#   https://github.com/LDNOOBW/List-of-Dirty-Naughty-Obscene-and-Otherwise-Bad-Words',
];

const here = dirname( fileURLToPath( import.meta.url ) );
const outPath = join( here, '..', 'assets', 'games', 'words.txt' );
mkdirSync( dirname( outPath ), { recursive: true } );
writeFileSync( outPath, header.join( '\n' ) + '\n' + picked.join( '\n' ) + '\n' );
console.log( `Wrote ${ picked.length } words to ${ outPath }` );
